export function getCurrentLanguage(): AppLanguage {
  return activeLanguage;
}

export function translate(language: AppLanguage, key: string, values: Values = {}): string {
  const template = catalogue[key]?.[language] ?? catalogue[key]?.ru ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

type LanguageContextValue = {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (key: string, values?: Values) => string;
};

const fallbackContext: LanguageContextValue = {
  language: "ru",
  setLanguage: () => undefined,
  t: (key, values) => translate("ru", key, values)
};

const LanguageContext = createContext<LanguageContextValue>(fallbackContext);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(() => {
    if (typeof window === "undefined") return "ru";
    // Russian by default on first boot (no stored preference yet) - this is
    // an internal Kazakhstani-operations tool, not an English-first product.
    // An explicit prior choice of English is still respected.
    const restored = window.sessionStorage.getItem(STORAGE_KEY) === "en" ? "en" : "ru";
    activeLanguage = restored;
    return restored;
  });

  const setLanguage = (next: AppLanguage) => setLanguageState(next);
  useEffect(() => {
    activeLanguage = language;
    window.sessionStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<LanguageContextValue>(
    () => ({ language, setLanguage, t: (key, values) => translate(language, key, values) }),
    [language]
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n(): LanguageContextValue {
  return useContext(LanguageContext);
}
